#!/usr/bin/env python3
"""Writes the translations of i18n/po/*.po into the files that can't call
gettext: the installer pages (module.conf `key[lang]:`), the install
slideshow (a lookup table in show.qml), .desktop files (`Name[lang]=`) and
the polkit policy (`xml:lang`). Run by i18n/build.sh; the results are
committed so the ISO build needs nothing extra.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "i18n"))
from extract import DESKTOP_FILES, yaml_block  # noqa: E402

# Calamares names some locales differently from glibc
CALAMARES_LANG = {"pt": "pt_PT"}


def read_po(path: Path) -> dict[str, str]:
    out: dict[str, str] = {}
    msgid = msgstr = None
    field = None

    def unq(s: str) -> str:
        return bytes(s, "utf-8").decode("unicode_escape").encode("latin-1").decode("utf-8")

    def flush():
        if msgid and msgstr:
            out[msgid] = msgstr

    for line in path.read_text().splitlines() + [""]:
        if line.startswith("msgid "):
            flush()
            msgid, msgstr, field = unq(line[7:-1]), None, "id"
        elif line.startswith("msgid_plural"):
            field = None
        elif line.startswith("msgstr ") or line.startswith("msgstr[0] "):
            msgstr = unq(line.split(" ", 1)[1][1:-1])
            field = "str"
        elif line.startswith('"'):
            if field == "id":
                msgid += unq(line[1:-1])
            elif field == "str":
                msgstr += unq(line[1:-1])
        elif not line.strip():
            flush()
            msgid = msgstr = None
            field = None
    return out


def catalogs() -> dict[str, dict[str, str]]:
    return {po.stem: read_po(po) for po in sorted((ROOT / "i18n/po").glob("*.po"))}


def yq(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def module_confs(cats: dict) -> None:
    for f in sorted(ROOT.glob("installer/calamares/modules/*/module.conf")):
        lines = [ln for ln in f.read_text().splitlines()
                 if not re.match(r"\s*(step|name|description)\[[\w@]+\]:", ln)]
        out, i = [], 0
        while i < len(lines):
            m = re.match(r"(\s*)(step|name|description):", lines[i])
            if not m:
                out.append(lines[i])
                i += 1
                continue
            val, j = yaml_block(lines, i)
            out += lines[i:j]
            for lang, cat in cats.items():
                t = cat.get(val)
                if t and t != val:
                    out.append(f"{m.group(1)}{m.group(2)}[{CALAMARES_LANG.get(lang, lang)}]: {yq(t)}")
            i = j
        f.write_text("\n".join(out) + "\n")


def slideshow(cats: dict) -> None:
    qml = ROOT / "installer/calamares/branding/staticlinux/show.qml"
    s = qml.read_text()
    texts = set()
    for key, val in re.findall(r'\b(title|body):\s*"((?:[^"\\]|\\.)*)"', s):
        texts.add(val.replace("\\n", "\n"))
    table = {lang: {t: cat[t] for t in sorted(texts) if t in cat} for lang, cat in cats.items()}
    block = ("    // i18n:begin (generated by i18n/apply.py from i18n/po/)\n"
             f"    readonly property var tr: {json.dumps(table, ensure_ascii=False, sort_keys=True)}\n"
             "    function t(s) {\n"
             "        var l = Qt.locale().name\n"
             "        if (l.indexOf(\"es\") === 0) return s\n"
             "        var d = tr[l] || tr[l.split(\"_\")[0]] || tr[\"en\"] || {}\n"
             "        return d[s] || s\n"
             "    }\n"
             "    // i18n:end\n")
    if "// i18n:begin" in s:
        s = re.sub(r"    // i18n:begin.*?// i18n:end\n", lambda _m: block, s, flags=re.S)
    else:
        s = s.replace("    function onActivate()", block + "\n    function onActivate()", 1)
    s = s.replace("text: root.slides[root.current].title", "text: root.t(root.slides[root.current].title)")
    s = s.replace("text: root.slides[root.current].body", "text: root.t(root.slides[root.current].body)")
    qml.write_text(s)


def desktop_files(cats: dict) -> None:
    for f in DESKTOP_FILES():
        lines = [ln for ln in f.read_text().splitlines()
                 if not re.match(r"(Name|GenericName|Comment)\[", ln)]
        out = []
        for ln in lines:
            out.append(ln)
            m = re.match(r"(Name|GenericName|Comment)=(.+)$", ln)
            if m:
                for lang, cat in cats.items():
                    t = cat.get(m.group(2))
                    if t and t != m.group(2):
                        out.append(f"{m.group(1)}[{lang}]={t}")
        f.write_text("\n".join(out) + "\n")


def polkit(cats: dict) -> None:
    for f in sorted(ROOT.glob("sl-welcome/data/*.policy")):
        lines = [ln for ln in f.read_text().splitlines() if "xml:lang=" not in ln]
        out = []
        for ln in lines:
            out.append(ln)
            m = re.match(r"(\s*)<(description|message)>(.+)</\2>", ln)
            if m:
                for lang, cat in cats.items():
                    t = cat.get(m.group(3))
                    if t and t != m.group(3):
                        t = t.replace("&", "&amp;").replace("<", "&lt;")
                        out.append(f'{m.group(1)}<{m.group(2)} xml:lang="{lang}">{t}</{m.group(2)}>')
        f.write_text("\n".join(out) + "\n")


def main() -> int:
    cats = catalogs()
    module_confs(cats)
    slideshow(cats)
    desktop_files(cats)
    polkit(cats)
    print(f"traducciones aplicadas: {', '.join(cats)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
