"""Generate the "StaticLinux" icon theme: Papirus, with folders in the theme's colour.

Papirus ships every folder icon in ~25 colours (folder-yellow.svg,
folder-yellow-music.svg, user-yellow-home.svg, ...). This theme inherits
Papirus and only adds symlinks that point the plain names (folder.svg,
folder-music.svg, user-home.svg) at the chosen colour, so nothing is copied
and a new Papirus release is picked up automatically.
"""

from __future__ import annotations

import re
from pathlib import Path

PAPIRUS = Path("/usr/share/icons/Papirus")
# XDG/freedesktop names that Papirus spells differently in its colour variants
ALIASES = {"folder-public.svg": ["folder-publicshare.svg"],
           "folder-download.svg": ["folder-downloads.svg"]}


def links(colour: str) -> dict[str, str]:
    """{relative link path: absolute target} for every folder icon of `colour`."""
    out: dict[str, str] = {}
    if not PAPIRUS.is_dir():
        return out
    pattern = re.compile(rf"^(folder|user)-{colour}(-[a-z0-9-]+)?\.svg$")
    for size_dir in sorted(PAPIRUS.iterdir()):
        places = size_dir / "places"
        if not places.is_dir():
            continue
        for icon in places.iterdir():
            m = pattern.match(icon.name)
            if not m:
                continue
            plain = f"{m.group(1)}{m.group(2) or ''}.svg"
            for name in [plain, *ALIASES.get(plain, [])]:
                out.setdefault(f"{size_dir.name}/places/{name}", str(icon.resolve()))
    return out


def index_theme(theme: dict[str, str], link_paths: list[str]) -> str:
    parent = "Papirus-Light" if theme["mode"] == "light" else "Papirus-Dark"
    dirs = sorted({str(Path(p).parent) for p in link_paths})
    lines = [
        "[Icon Theme]",
        f"Name=StaticLinux",
        f"Comment=Papirus with {theme['folders']} folders (generated by sl-theme)",
        f"Inherits={parent},hicolor",
        f"Directories={','.join(dirs)}",
        "",
    ]
    for d in dirs:
        size = d.split("/")[0]
        scale = 2 if "@2x" in size else 1
        px = size.split("x")[0] if size[0].isdigit() else "48"
        lines += [f"[{d}]", "Context=Places", f"Size={px}", f"Scale={scale}",
                  "Type=Scalable" if size == "symbolic" else "Type=Fixed", ""]
    return "\n".join(lines)
